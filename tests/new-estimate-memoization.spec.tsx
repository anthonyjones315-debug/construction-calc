import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";

describe("NewEstimateClient memoization and rendering", () => {
  it("verifies PriceBookPanel filters and groups materials by category correctly", () => {
    // Test category grouping logic
    const materials = [
      { id: "1", material_name: "Concrete Bag", category: "Masonry", unit_type: "bag", unit_cost: 12.5 },
      { id: "2", material_name: "2x4 Lumber", category: "Framing", unit_type: "ea", unit_cost: 8.0 },
      { id: "3", material_name: "Mortar Mix", category: "Masonry", unit_type: "bag", unit_cost: 15.0 },
    ];

    const query = "masonry";
    const q = query.trim().toLowerCase();
    const filtered = materials.filter(
      (m) =>
        m.material_name.toLowerCase().includes(q) ||
        m.category.toLowerCase().includes(q),
    );

    const map: Record<string, typeof materials> = {};
    for (const m of filtered) {
      const cat = m.category || "Other";
      if (!map[cat]) map[cat] = [];
      map[cat].push(m);
    }

    expect(filtered).toHaveLength(2);
    expect(Object.keys(map)).toEqual(["Masonry"]);
    expect(map.Masonry).toHaveLength(2);
  });

  it("verifies autoGeneratedName formatting logic for EstimateDetailsCard", () => {
    function computeAutoGeneratedName(clientName: string, projectName: string, estimateName: string) {
      const lastName = clientName.trim().split(/\s+/).pop() || "";
      const project = projectName.trim();
      if (!lastName && !project) return estimateName || "";
      if (lastName && !project) return lastName;
      if (!lastName && project) return project;
      return `${lastName} - ${project}`;
    }

    expect(computeAutoGeneratedName("John Smith", "Kitchen Remodel", "")).toBe("Smith - Kitchen Remodel");
    expect(computeAutoGeneratedName("Alice", "", "Draft 1")).toBe("Alice");
    expect(computeAutoGeneratedName("", "Deck Build", "Draft 1")).toBe("Deck Build");
    expect(computeAutoGeneratedName("", "", "Fallback Name")).toBe("Fallback Name");
  });
});
